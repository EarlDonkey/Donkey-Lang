import os

# The order matters: lexer -> parser -> interpreter -> compiler -> vm
files = [
    "lib/strings.donk", # lexer depends on slice()
    "compiler/lexer.donk",
    "compiler/parser.donk",
    "compiler/interpreter.donk",
    "compiler/bytecode_compiler.donk",
    "compiler/bytecode_vm.donk",
]

out_lines = []
out_lines.append("// --- AUTOGENERATED DONKYC BOOTSTRAP ---")
out_lines.append("// Do not edit this file directly. Edit the files in compiler/ instead.")
out_lines.append("")

for filepath in files:
    if not os.path.exists(filepath):
        print(f"Error: {filepath} not found.")
        exit(1)
        
    out_lines.append(f"// --- Begin {filepath} ---")
    with open(filepath, "r", encoding="utf-8") as f:
        for line in f:
            # Strip imports so we don't get duplicate definitions
            if line.strip().startswith("import "):
                continue
            out_lines.append(line.rstrip())
    out_lines.append(f"// --- End {filepath} ---\n")

# Append the main entry point
main_code = """
// --- Main Entry Point ---
if len(args) < 2 {
    print("Usage: donkyc <run|compile> <file.donk>");
} else {
    let cmd = args[0];
    let path = args[1];
    let src = read_file(path);
    
    try {
        let tokens = tokenize(src);
        let ast = parse_program(tokens);
        
        if cmd == "run" {
            let global_env = new_env("");
            exec_stmt(ast, global_env);
        } else if cmd == "compile" {
            let bytecode = compile_ast(ast);
            let json_str = to_json(bytecode);
            write_file(path + ".json", json_str);
            print("Compiled to " + path + ".json");
        } else {
            print("Unknown command: " + cmd);
        }
    } catch e {
        print("Error: " + e);
    }
}
"""
out_lines.append(main_code)

with open("compiler/donkyc.donk", "w", encoding="utf-8") as f:
    f.write("\n".join(out_lines))

print("Successfully built compiler/donkyc.donk!")